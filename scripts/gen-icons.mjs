// Extracts only the brand icon paths we use from `simple-icons` so the library itself is never bundled.
// Run once after changing the list:  node scripts/gen-icons.mjs
import * as si from 'simple-icons'
import { writeFileSync } from 'node:fs'

const wanted = {
  python: 'siPython', flask: 'siFlask', laravel: 'siLaravel', php: 'siPhp', react: 'siReact', nextjs: 'siNextdotjs',
  flutter: 'siFlutter', dart: 'siDart', android: 'siAndroid', figma: 'siFigma', claude: 'siClaude',
  postgresql: 'siPostgresql', mysql: 'siMysql', typescript: 'siTypescript', nodejs: 'siNodedotjs',
  tailwind: 'siTailwindcss', docker: 'siDocker', github: 'siGithub', x: 'siX', whatsapp: 'siWhatsapp',
}
const out = {}
for (const [k, exp] of Object.entries(wanted)) {
  const icon = si[exp]
  if (!icon) throw new Error(`missing icon ${exp}`)
  out[k] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path }
}
writeFileSync(
  new URL('../src/lib/brand-paths.ts', import.meta.url),
  `// GENERATED by scripts/gen-icons.mjs from simple-icons (CC0). Do not edit by hand.\nexport const BRAND_PATHS: Record<string, { title: string; hex: string; path: string }> = ${JSON.stringify(out, null, 2)}\n`,
)
console.log('wrote', Object.keys(out).length, 'icons')
